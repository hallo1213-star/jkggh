import { PARTS, buildShow } from '../../tiktok.js';
import { cloudTools } from '../../cloud-tools.js';
const assert = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) process.exitCode = 1; };
const tools = cloudTools.map((t) => t.name);
const info = { tools, laptopTools: 12, laptop: false, voice: 'Deepgram' };
const shows = [1, 2, 3, 4, 5].map((p) => buildShow(info, p));
assert(PARTS === 5 && shows.every((s, i) => s.part === i + 1), '5 Teile');
assert(shows.every((s) => s.scenes.length >= 4 && s.scenes[0].key === 'intro' && s.scenes.at(-1).key === 'outro'), 'jeder Teil: Intro … Outro, mindestens 4 Szenen');
assert(shows.slice(1).every((s, i) => s.scenes[0].title === `PART ${i + 2}` && s.scenes[0].part === i + 2), 'Teil 2–5 zeigen „PART n“');
assert(shows.slice(0, 4).every((s, i) => s.scenes.at(-1).line.includes(`Part ${i + 2}`)) && /Finale/.test(shows[4].scenes.at(-1).line), 'Outro kündigt den nächsten Teil an, Teil 5 ist das Finale');
const lines = shows.map((s) => s.scenes.map((x) => x.line).join(' '));
assert(new Set(lines).size === 5, 'jeder Teil hat andere Inhalte');
assert(shows.every((s) => s.scenes.every((x) => x.line.length <= 290 && !/\bund und\b/.test(x.line))), 'Sätze sind kurz genug und sauber');
assert(buildShow(info, 9).part === 5 && buildShow(info, 0).part === 1 && buildShow(info).part === 1, 'ungültige Teil-Nummern werden begrenzt');
const few = buildShow({ tools: ['get_weather'], laptopTools: 0 }, 2);
assert(few.scenes.every((x) => !/Anzug|Laser|Kinoplakat/.test(x.line)), 'fehlt eine Funktion, wird sie nicht erwähnt (nichts erfunden)');
const tool = cloudTools.find((t) => t.name === 'tiktok_show'); const shown = []; const ctx = { systemsInfo: () => info, showVisual: (m) => shown.push(m) };
await tool.run({ action: 'start', part: 3 }, ctx);
assert(shown[0].part === 3 && ctx.tiktok.lines[0].startsWith('Part drei'), 'Werkzeug startet Part 3 und merkt sich die Sätze');
