process.env.JARVIS_PASSWORD = 'geheim-passwort-123';
const a = await import('../../auth.js');
const assert = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) process.exitCode = 1; };
const cookie = a.sessionCookie(true);
assert(/HttpOnly; SameSite=Strict; Max-Age=\d+; Secure$/.test(cookie), 'cookie flags');
const value = cookie.split(';')[0];
assert(a.isAuthenticated({ headers: { cookie: value } }), 'valid cookie accepted');
assert(!a.isAuthenticated({ headers: { cookie: value.replace(/.$/, c => c === 'A' ? 'B' : 'A') } }), 'tampered signature rejected');
const exp = String(Date.now() - 1000);
assert(!a.isAuthenticated({ headers: { cookie: `jarvis_session=${exp}.xyz` } }), 'forged/expired rejected');
assert(!a.isAuthenticated({ headers: {} }), 'no cookie rejected');
for (let i = 1; i <= 4; i++) assert(!a.attemptLogin('1.2.3.4', 'falsch').locked, `fail ${i} not locked`);
const fifth = a.attemptLogin('1.2.3.4', 'falsch');
assert(fifth.locked, 'locked after 5 failures');
assert(a.attemptLogin('1.2.3.4', 'geheim-passwort-123').locked, 'even correct password refused while locked');
assert(a.attemptLogin('5.6.7.8', 'geheim-passwort-123').ok, 'other client logs in');
assert(a.tokenMatches('Bearer tok123', 'tok123') && !a.tokenMatches('Bearer nope', 'tok123') && !a.tokenMatches('Bearer tok123', undefined), 'laptop token check');
process.env.JARVIS_PASSWORD = 'kurz';
assert(!a.passwordConfigured() && !a.isAuthenticated({ headers: { cookie: value } }), 'short password disables login');
