import { sanitizeList, addItems, removeItems, listAsText, shopLinks } from '../../shopping.js';
const assert = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) process.exitCode = 1; };
let { list, added } = addItems([], ['Milch', ' Brot ', 'milch', '', 'Hafermilch']);
assert(JSON.stringify(list.map(i => i.text)) === '["Milch","Brot","Hafermilch"]' && added.length === 3, 'add with trim + case-insensitive duplicates');
list[1].done = true;
({ list } = addItems(list, ['brot']));
assert(list[1].done === false, 're-adding a ticked item un-ticks it');
let r = removeItems(list, ['milch']);
assert(JSON.stringify(r.removed) === '["Milch"]' && r.list.some(i => i.text === 'Hafermilch'), 'exact match wins over partial');
r = removeItems(r.list, ['hafer', 'Käse']);
assert(JSON.stringify(r.removed) === '["Hafermilch"]' && JSON.stringify(r.notFound) === '["Käse"]', 'partial match + not found reported');
const amb = removeItems(sanitizeList(['Vollmilch', 'Hafermilch']), ['milch']);
assert(amb.removed.length === 0 && amb.notFound[0] === 'milch', 'ambiguous partial match removes nothing');
const many = sanitizeList(Array.from({ length: 150 }, (_, i) => ({ text: `Artikel ${i}`, done: i % 2 === 0 })));
assert(many.length === 100, 'list capped at 100');
assert(sanitizeList([{ text: '<b>x</b>\n\ty' }, 42, null])[0].text === '<b>x</b> y', 'control chars removed, junk ignored (rendered as text)');
assert(listAsText(sanitizeList([{ text: 'A', done: true }, 'B'])) === '☐ B\n☑ A', 'text export: open first, done last');
const links = shopLinks('Kopfhörer & Kabel');
assert(links.length === 3 && links.every(l => l.url.startsWith('https://')) && links[0].url.includes('Kopfh%C3%B6rer%20%26%20Kabel'), 'shop links https and URL-encoded');
